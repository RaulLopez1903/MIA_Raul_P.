import numpy as np
import numpy.random as rnd
import matplotlib.pyplot as plt
import imageio.v2

# Cargamos una imagen
img = np.asarray(imageio.imread('Emiliano_Zapata.jpg'))

#Convertimos la imagen a una imagen monocromática
img = np.round(np.mean(img,2)).astype(np.uint8)

#Convertimos la imagen a una imagen monocromática
rows, cols = img.shape
tama = rows * cols

#Calcula el histograma de la image
H = np.zeros(256)
for pix in img.reshape(tama):
    H[pix] += 1

fig1, ax1 = plt.subplots(1, 2, figsize=(8, 4), layout='constrained')

ax1[0].imshow(img,cmap='gray')
ax1[0].set(xlabel='columnas', ylabel='renglones',
       title='El General Emiliano Zapata')

ax1[1].plot(np.arange(256), H)
ax1[1].set(xlabel='valor de pixeles en la imagen', ylabel='# de pixeles asociado al valor del pixel.',
       title='Histograma de la imagen')
plt.show()

# Definimos el umbral como un valor aleatorio en el rango [0,255]
umbral = rnd.randint(0,256)
umbral = 200

# Calculamos el valor promedio del Fondo y de la Figura.
promFondo = promFigura = np.float32(0)
contFondo = contFigura = cont = np.float32(0)

for pix in img.reshape(tama):
  cont +=1
  if pix > umbral:
    promFondo += pix
    contFondo +=1
  else:
    promFigura += pix
    contFigura +=1

promFigura = promFigura / contFigura
promFondo = promFondo / contFondo

# Definimos el úmbral como el promedio entre el valor promedio del fondo
# y el valor promedio de la figura.
umbral = np.round((promFigura + promFondo) / 2).astype(np.uint8)
print ("El valor de umbral es:", umbral)

# Umbralizamos la imagen
imgU = img.copy()
imgU = imgU.reshape(tama)
for i in range(tama):
  if imgU[i] > umbral:
    imgU[i] = 255
  else:
    imgU[i] = 0
imgU = imgU.reshape(rows,cols)


#Graficamos la Imagen
fig2, ax2 = plt.subplots(1, 2, figsize=(10, 5), layout='constrained')

ax2[0].imshow(imgU, cmap='gray')
ax2[0].set(xlabel='columnas', ylabel='renglones',
       title='Emiliano Zapata Umbralizado (um=%3.0f)'% umbral)

ax2[1].plot(np.arange(256), H,umbral,H[umbral],'*r')
ax2[1].set(xlabel='valor de pixeles en la imagen', ylabel='# de pixeles asociado al valor del pixel.',
       title='Histograma de la imagen')
plt.show()

