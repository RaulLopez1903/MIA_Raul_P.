# Calcula la distancia euclideana al cuadrado entre los vectores 'x' y 'y'.
def dEuclidSq(x,y):
  #dfV es la diferencia de los vectores
  dfV = x-y
  # El producto punto entre dfv y si mismo es equivalente
  # a la sumatoria del cuadrado de lo elementos de dfv
  # esto es, la distancia euclideana al cuadrado.
  return np.dot(dfV, dfV)


def Kmeans(p, K, itMax = 30):
  # n es el número de datos que tenemos.
  # se asume que p es una matriz con n columnas
  # donde cada una ella representa un dato.
  # El número de renlones de p corresponde al
  # número de dimensiones del arreglo.
  d, n = p.shape

  # c es u arreglo que define la clase a la que pertenece cada
  c = rnd.randint(0, K, n)

  # C es la matriz donde almacenaremos los centroides de las
  # clases que encontremos. Cada columna corresponde a un centroide.
  C=np.zeros((d, K))



  #Calculamos los Centroides Iniciales
  cont=np.zeros(K)
  for i in range(n):
    idx = c[i]
    C[:, idx] += p[:,i]
    cont[idx] += 1
  for i in range(K):
    if cont[i] != 0:
      C[:,i] /= cont[i]
    else:
      print("Error: Clase vacía")

  # En esta matriz almacenaremos el historial de los centroides.
  evolC = np.zeros((K * d,itMax+1))

  idx = 0
  for i in range(K):
    evolC[idx:idx+d,0] = C[:,i]
    idx += d


  # La variable cambio indica si hubo algun cambio en la definicion
  # de los centroides entre iteraciones.
  cambio = True
  iteracion = 0 # Contadore de iteraciones

  # Ciclo principal del programa
  while iteracion < itMax and cambio == True:
    print("Iteracion #", iteracion)

    #Calculamos las distancias entre cada punto y cada clase.
    for i in range(n):
      closest = 0
      difMin = dEuclidSq(p[:,i], C[:,0])
      for j in range(1,K):
        dif = dEuclidSq(p[:,i], C[:,j])
        if dif < difMin:
          difMin = dif
          closest = j
      c[i] = closest

    #Almacenamo el valor de los centroides en el historial.
    idx = 0
    for i in range(K):
      evolC[idx:idx+d, iteracion+1] = C[:,i]
      idx += d

    #Recalculamos los Centroides
    C_Old = C.copy()
    C=np.zeros((d, K))
    cont=np.zeros(K)
    for i in range(n):
      idx = c[i]
      C[:, idx] += p[:,i]
      cont[idx] += 1
    for i in range(K):
      if cont[i] != 0:
        C[:,i] /= cont[i]
      else:
        print("Error: Clase vacía")

    #Si no hubo cambios terminamos
    if (C_Old == C).all():
      cambio = False
    iteracion += 1

  return C, evolC[:,:iteracion+1]

k = 6
