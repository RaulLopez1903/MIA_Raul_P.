K=6

# Creamos Puntos aleatorios en 2 dimensiones que correspondan a K clase.

# Cada columna de la matriz almacena las coordenada promedio de la clase
# la varianza de la clase y cuantos puntos la conforman
C=np.zeros((4,K))

# Definimos los centroides como valores aleatorios en el rango
# x \in [0, xMax)
# y \in [0, yMax)
# La desviación estandar asociada a cada cumulo es un valor en el intervalo [sMin, sMax).
# El numero de puntos asociados a cada clase es un numero en el interval [nMin,nMax)
#
# Cada columna de la matriz C codifica los parametros de cada clase descritos arriba.
xMin, xMax, yMin, yMax, = -1000, 1000, -1000, 1000,
sMin, sMax, nMin, nMax = 40, 60, 70, 100
for i in range(K):
  C[:,i]= [rnd.randint(xMin, xMax),rnd.randint(yMin, yMax),\
           rnd.randint(sMin, sMax), rnd.randint(nMin, nMax)]

# N es el numero de datos que vamos a considerer
N = np.int32(np.sum(C[3,:]))

# Generamos los puntos
# Cada columna de la matriz p almacena un dato.
p = np.zeros((2,N))
# Cada elementos del arreglo c indica la clase a la que corresponde
c = np.zeros(N)
